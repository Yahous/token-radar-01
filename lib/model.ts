// Token Radar's model, version radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// early radar: pre-token protocols below the watchlist floor, strongest TVL first. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol). Live-token
// protocols are kept apart and shown as the market's own values, never mixed into the ranked board.
// The snapshot says a protocol "records no token"; it never proves it has none.
//
// Implied value follows only from the snapshot's own figures, through one function that scores every
// row. No protocol name is ever special-cased:
//
//   size       = tvl_usd x BASE_MULTIPLE
//   growth     = clamp(change_7d, -80, 300) per cent; a missing change counts as 0
//   growthMult = 1 + GROWTH_WEIGHT x sign(growth) x sqrt(|growth| / 100)
//                A square root, not a line: a week of +40% lifts the value, a week of +4000% does not
//                lift it a hundred times more. One-week spikes are noise; sustained size is signal.
//   maturity   = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS x MATURITY_RANGE
//                age_days is the days from listed_at to the snapshot's as_of; unknown age counts as
//                UNKNOWN_AGE_DAYS. A protocol that has run for years with no token has had longer to
//                build the habit of rewarding its users, and a launch would price a longer record.
//   category   = 0.85 for a wrapped, staked or bridged product (Bridge, Canonical Bridge, Liquid
//                Staking, Liquid Restaking, Restaked BTC, CEX), 1.0 otherwise: the value of such a
//                product mostly belongs to the token that already trades, not to a new one.
//   implied    = max(1, round(size x growthMult x maturity x category))
//
// The constants are the model's, stated in the dashboard and changeable in its sandbox. The page
// recomputes every row from the same figures, so the board and the page are the same arithmetic.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them and the sandbox may change them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  wrapper_factor: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.22,
  growth_weight: 0.5,
  growth_floor: -80,
  growth_cap: 300,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1460,
  unknown_age_days: 365,
  wrapper_factor: 0.85,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live token view carries, by market cap. */
